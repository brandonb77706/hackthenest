import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it, vi } from "vitest";
import { GroceryShopping } from "./GroceryShopping";
import type { GroceryCatalog } from "./catalog";

vi.mock("@/components/ReadAloudButton", () => ({ ReadAloudButton: ({ label }: { label: string }) => <button>{label}</button> }));
it("asks permission and searches stores around the device coordinates", async () => {
  const user = userEvent.setup();
  const storesNear = vi.fn().mockResolvedValue([{ locationId: "near", name: "Nearby store" }]);
  Object.defineProperty(navigator, "geolocation", { configurable: true, value: { getCurrentPosition: (success: PositionCallback) => success({ coords: { latitude: 42.2, longitude: -83.6 } as GeolocationCoordinates } as GeolocationPosition) } });
  render(<GroceryShopping catalog={{ stores: async () => [], storesNear, search: async () => [] }} />);
  await user.click(screen.getByRole("button", { name: "Use my precise location" }));
  expect(await screen.findByRole("option", { name: "Nearby store" })).toBeInTheDocument();
  expect(storesNear).toHaveBeenCalledWith(42.2, -83.6);
});
it("selects a store, searches, adds and removes a product with accessible labels", async () => {
  const user = userEvent.setup();
  const catalog: GroceryCatalog = { stores: async () => [{ locationId: "123", name: "Demo" }], storesNear: async () => [], search: vi.fn().mockResolvedValue([{ id: "1", name: "Bread", availability: "unknown", aisle: null }]) };
  render(<GroceryShopping catalog={catalog} />);
  await user.type(screen.getByLabelText("ZIP code"), "48197");
  await user.click(screen.getByRole("button", { name: "Find stores" }));
  await user.selectOptions(await screen.findByRole("option", { name: "Demo" }).then(() => screen.getByLabelText("Choose a store")), "123");
  await user.type(screen.getByLabelText("Find an item"), "bread");
  await user.click(screen.getByRole("button", { name: "Search products" }));
  expect(catalog.search).toHaveBeenCalledWith("123", "bread");
  expect(await screen.findByText("Availability unknown")).toBeInTheDocument();
  expect(screen.getByText("Aisle unavailable")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "Read help phrase for Bread" })).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "Add Bread" }));
  expect(screen.getByRole("button", { name: "Add Bread" })).toBeDisabled();
  const cart = screen.getByRole("button", { name: "View shopping list (1 item)" });
  expect(cart).toHaveAttribute("aria-expanded", "false");
  await user.click(cart);
  expect(screen.getByRole("button", { name: "Hide shopping list (1 item)" })).toHaveAttribute("aria-expanded", "true");
  expect(screen.getByRole("table", { name: "Shopping list with product availability and aisle" })).toBeInTheDocument();
  expect(screen.getByRole("columnheader", { name: "Aisle" })).toBeInTheDocument();
  expect(screen.getByRole("cell", { name: "Aisle unavailable" })).toBeInTheDocument();
  const checkbox = screen.getByRole("checkbox", { name: "Got it: Bread" });
  expect(checkbox).not.toBeChecked();
  await user.click(checkbox);
  expect(checkbox).toBeChecked();
  await user.click(screen.getByRole("button", { name: "Hide shopping list (1 item)" }));
  await user.click(screen.getByRole("button", { name: "View shopping list (1 item)" }));
  expect(screen.getByRole("checkbox", { name: "Got it: Bread" })).toBeChecked();
  await user.click(screen.getByRole("button", { name: "Remove Bread" }));
  expect(screen.getByText("No items yet.")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "Hide shopping list (0 items)" }));
  expect(screen.getByRole("button", { name: "View shopping list (0 items)" })).toHaveAttribute("aria-expanded", "false");
  await user.click(screen.getByRole("button", { name: "Add Bread" }));
  await user.click(screen.getByRole("button", { name: "View shopping list (1 item)" }));
  expect(screen.getByRole("checkbox", { name: "Got it: Bread" })).not.toBeChecked();
});
it("clears the list when switching stores and reports a failed search", async () => {
  const user = userEvent.setup();
  const catalog: GroceryCatalog = { stores: async () => [{ locationId: "1", name: "One" }, { locationId: "2", name: "Two" }], storesNear: async () => [], search: vi.fn().mockResolvedValueOnce([{ id: "x", name: "Milk", availability: "unavailable", aisle: null }]).mockRejectedValueOnce(new Error("offline")) };
  render(<GroceryShopping catalog={catalog} />);
  await user.type(screen.getByLabelText("ZIP code"), "48197");
  await user.click(screen.getByRole("button", { name: "Find stores" }));
  await screen.findByRole("option", { name: "One" });
  await user.selectOptions(screen.getByLabelText("Choose a store"), "1");
  await user.type(screen.getByLabelText("Find an item"), "milk");
  await user.click(screen.getByRole("button", { name: "Search products" }));
  await user.click(await screen.findByRole("button", { name: "Add Milk" }));
  await user.selectOptions(screen.getByLabelText("Choose a store"), "2");
  await user.click(screen.getByRole("button", { name: "View shopping list (0 items)" }));
  expect(screen.getByText("No items yet.")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "Search products" }));
  expect(await screen.findByRole("status")).toHaveTextContent("Search is unavailable");
});
